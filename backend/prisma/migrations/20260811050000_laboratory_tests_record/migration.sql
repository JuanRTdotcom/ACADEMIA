CREATE TABLE nucleo.pruebas_laboratorio (
  id_pruebas_laboratorio uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  fid_organizaciones uuid NOT NULL,
  fid_categorias_pruebas_laboratorio uuid NOT NULL,
  nombre varchar(220) NOT NULL,
  estado integer NOT NULL DEFAULT 1 CHECK (estado IN (0, 1)),
  created_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_by text,
  updated_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_by text,
  eliminado_en timestamptz(3),
  eliminado_por uuid,
  CONSTRAINT pruebas_laboratorio_nombre_check CHECK (char_length(btrim(nombre)) BETWEEN 2 AND 220),
  CONSTRAINT pruebas_laboratorio_organizacion_fk FOREIGN KEY (fid_organizaciones) REFERENCES nucleo.organizaciones(id_organizaciones) ON DELETE CASCADE,
  CONSTRAINT pruebas_laboratorio_categoria_fk FOREIGN KEY (fid_categorias_pruebas_laboratorio) REFERENCES configuracion.categorias_pruebas_laboratorio(id_categorias_pruebas_laboratorio) ON DELETE RESTRICT,
  CONSTRAINT pruebas_laboratorio_id_organizacion_unique UNIQUE (id_pruebas_laboratorio, fid_organizaciones)
);
CREATE INDEX pruebas_laboratorio_organizacion_idx ON nucleo.pruebas_laboratorio(fid_organizaciones, eliminado_en, estado, created_at DESC);
CREATE INDEX pruebas_laboratorio_categoria_idx ON nucleo.pruebas_laboratorio(fid_categorias_pruebas_laboratorio, estado, nombre);
CREATE UNIQUE INDEX pruebas_laboratorio_nombre_activo_unique ON nucleo.pruebas_laboratorio(fid_organizaciones, fid_categorias_pruebas_laboratorio, upper(btrim(nombre))) WHERE eliminado_en IS NULL;
CREATE TRIGGER establecer_updated_at BEFORE UPDATE ON nucleo.pruebas_laboratorio FOR EACH ROW EXECUTE FUNCTION configuracion.establecer_updated_at();

