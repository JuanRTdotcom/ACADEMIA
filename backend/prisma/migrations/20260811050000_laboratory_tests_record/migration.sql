SELECT organizacion.id_organizaciones, base.fid_categorias_pruebas_laboratorio, base.nombre, 'migration', 'migration'
FROM nucleo.organizaciones organizacion CROSS JOIN configuracion.catalogo_pruebas_laboratorio_base base
WHERE organizacion.estado = 1 AND organizacion.eliminado_en IS NULL AND base.estado = 1;

CREATE TABLE personas.pruebas_registro_laboratorio (
  id_pruebas_registro_laboratorio uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  fid_organizaciones uuid NOT NULL,
  fid_registros_atencion uuid NOT NULL,
  fid_pruebas_laboratorio uuid NOT NULL,
  fid_usuarios_profesional uuid NOT NULL,
  cantidad integer NOT NULL DEFAULT 1 CHECK (cantidad BETWEEN 1 AND 999),
  orden integer NOT NULL DEFAULT 0 CHECK (orden BETWEEN 0 AND 19),
  estado integer NOT NULL DEFAULT 1 CHECK (estado IN (0, 1)),
  created_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_by text,
  updated_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_by text,
  CONSTRAINT pruebas_registro_laboratorio_id_organizacion_unique UNIQUE (id_pruebas_registro_laboratorio, fid_organizaciones),
  CONSTRAINT pruebas_registro_laboratorio_registro_fk FOREIGN KEY (fid_registros_atencion, fid_organizaciones) REFERENCES personas.registros_atencion(id_registros_atencion, fid_organizaciones) ON DELETE RESTRICT,
  CONSTRAINT pruebas_registro_laboratorio_prueba_fk FOREIGN KEY (fid_pruebas_laboratorio, fid_organizaciones) REFERENCES nucleo.pruebas_laboratorio(id_pruebas_laboratorio, fid_organizaciones) ON DELETE RESTRICT,
  CONSTRAINT pruebas_registro_laboratorio_profesional_fk FOREIGN KEY (fid_usuarios_profesional, fid_organizaciones) REFERENCES seguridad.usuarios(id_usuarios, fid_organizaciones) ON DELETE RESTRICT
);
CREATE INDEX pruebas_registro_laboratorio_registro_idx ON personas.pruebas_registro_laboratorio(fid_registros_atencion, orden);
CREATE INDEX pruebas_registro_laboratorio_prueba_idx ON personas.pruebas_registro_laboratorio(fid_pruebas_laboratorio);
CREATE INDEX pruebas_registro_laboratorio_profesional_idx ON personas.pruebas_registro_laboratorio(fid_usuarios_profesional);
CREATE TRIGGER establecer_updated_at BEFORE UPDATE ON personas.pruebas_registro_laboratorio FOR EACH ROW EXECUTE FUNCTION configuracion.establecer_updated_at();

ALTER TABLE personas.adjuntos_registro_atencion ADD COLUMN fid_pruebas_registro_laboratorio uuid;
ALTER TABLE personas.adjuntos_registro_atencion ADD CONSTRAINT adjuntos_prueba_laboratorio_tenant_fk
  FOREIGN KEY (fid_pruebas_registro_laboratorio, fid_organizaciones)
  REFERENCES personas.pruebas_registro_laboratorio(id_pruebas_registro_laboratorio, fid_organizaciones) ON DELETE RESTRICT;
CREATE INDEX adjuntos_prueba_laboratorio_idx ON personas.adjuntos_registro_atencion(fid_pruebas_registro_laboratorio, eliminado_en);

