CREATE TABLE configuracion.categorias_pruebas_laboratorio (
  id_categorias_pruebas_laboratorio uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  codigo varchar(80) NOT NULL UNIQUE,
  nombre varchar(140) NOT NULL,
  orden integer NOT NULL DEFAULT 0,
  estado integer NOT NULL DEFAULT 1 CHECK (estado IN (0, 1)),
  created_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_by text,
  updated_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_by text
);
CREATE INDEX categorias_pruebas_laboratorio_estado_idx ON configuracion.categorias_pruebas_laboratorio(estado, orden, nombre);
CREATE TRIGGER establecer_updated_at BEFORE UPDATE ON configuracion.categorias_pruebas_laboratorio FOR EACH ROW EXECUTE FUNCTION configuracion.establecer_updated_at();

CREATE TABLE configuracion.catalogo_pruebas_laboratorio_base (
  id_catalogo_pruebas_laboratorio_base uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  fid_categorias_pruebas_laboratorio uuid NOT NULL REFERENCES configuracion.categorias_pruebas_laboratorio(id_categorias_pruebas_laboratorio) ON DELETE RESTRICT,
  nombre varchar(220) NOT NULL,
  orden integer NOT NULL DEFAULT 0,
  estado integer NOT NULL DEFAULT 1 CHECK (estado IN (0, 1)),
  created_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_by text,
  updated_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_by text,
  CONSTRAINT catalogo_pruebas_laboratorio_base_nombre_check CHECK (char_length(btrim(nombre)) BETWEEN 2 AND 220)
);
CREATE INDEX catalogo_pruebas_laboratorio_base_categoria_idx ON configuracion.catalogo_pruebas_laboratorio_base(fid_categorias_pruebas_laboratorio, estado, orden);
CREATE UNIQUE INDEX catalogo_pruebas_laboratorio_base_unique ON configuracion.catalogo_pruebas_laboratorio_base(fid_categorias_pruebas_laboratorio, upper(btrim(nombre)));
