INSERT INTO configuracion.admin_level_3 (
  id_admin_level_3, fid_admin_level_1, fid_admin_level_2, codigo, nombre, estado, created_by, updated_by
)
SELECT gen_random_uuid(), nivel_1.id_admin_level_1, nivel_2.id_admin_level_2,
       catalogo.codigo, catalogo.nombre, 1, 'migration', 'migration'
FROM catalogo_peru_nivel_3 catalogo
JOIN configuracion.admin_level_0 pais ON pais.codigo_iso2 = 'PE'
JOIN configuracion.admin_level_1 nivel_1
  ON nivel_1.fid_admin_level_0 = pais.id_admin_level_0
 AND nivel_1.codigo = LEFT(catalogo.codigo, 2)
JOIN configuracion.admin_level_2 nivel_2
  ON nivel_2.fid_admin_level_1 = nivel_1.id_admin_level_1
 AND nivel_2.codigo = LEFT(catalogo.codigo, 4)
ON CONFLICT (fid_admin_level_1, codigo) DO UPDATE
SET fid_admin_level_2 = EXCLUDED.fid_admin_level_2,
    nombre = EXCLUDED.nombre,
    estado = 1,
    updated_by = 'migration';

DO $$
DECLARE
  cantidad_paises INTEGER;
  cantidad_nivel_1 INTEGER;
  cantidad_nivel_2 INTEGER;
  cantidad_nivel_3 INTEGER;
BEGIN
  SELECT COUNT(*) INTO cantidad_paises
  FROM configuracion.admin_level_0
  WHERE estado = 1;

  SELECT COUNT(*) INTO cantidad_nivel_1
  FROM configuracion.admin_level_1 nivel
  JOIN configuracion.admin_level_0 pais
    ON pais.id_admin_level_0 = nivel.fid_admin_level_0
  WHERE pais.codigo_iso2 = 'PE' AND nivel.estado = 1;

  SELECT COUNT(*) INTO cantidad_nivel_2
  FROM configuracion.admin_level_2 nivel_2
  JOIN configuracion.admin_level_1 nivel_1
    ON nivel_1.id_admin_level_1 = nivel_2.fid_admin_level_1
  JOIN configuracion.admin_level_0 pais
    ON pais.id_admin_level_0 = nivel_1.fid_admin_level_0
  WHERE pais.codigo_iso2 = 'PE' AND nivel_2.estado = 1;

  SELECT COUNT(*) INTO cantidad_nivel_3
  FROM configuracion.admin_level_3 nivel_3
  JOIN configuracion.admin_level_1 nivel_1
    ON nivel_1.id_admin_level_1 = nivel_3.fid_admin_level_1
  JOIN configuracion.admin_level_0 pais
    ON pais.id_admin_level_0 = nivel_1.fid_admin_level_0
  WHERE pais.codigo_iso2 = 'PE' AND nivel_3.estado = 1;

  IF cantidad_paises < 249
     OR cantidad_nivel_1 <> 25
     OR cantidad_nivel_2 <> 196
     OR cantidad_nivel_3 <> 1892 THEN
    RAISE EXCEPTION
      'Catálogos incompletos: países %, departamentos %, provincias %, distritos %',
      cantidad_paises, cantidad_nivel_1, cantidad_nivel_2, cantidad_nivel_3;
  END IF;
END $$;
