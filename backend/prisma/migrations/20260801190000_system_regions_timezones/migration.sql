-- PostgreSQL usa la base IANA incluida en su tzdata. Se excluyen únicamente
-- identificadores internos que no representan zonas elegibles por un usuario.
INSERT INTO system.zonas_horarias (
  nombre_iana,
  created_by,
  updated_by
)
SELECT name, 'migration', 'migration'
FROM pg_timezone_names
WHERE name !~ '^(posix|right)/'
  AND name NOT IN ('Factory', 'localtime', 'posixrules')
ORDER BY name;

