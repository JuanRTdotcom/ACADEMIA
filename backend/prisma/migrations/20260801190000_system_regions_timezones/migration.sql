-- Catálogos globales ajenos a un tenant.
CREATE SCHEMA IF NOT EXISTS system;

CREATE TABLE system.paises (
  id_paises uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  codigo_iso2 char(2) NOT NULL UNIQUE,
  nombre_es text NOT NULL,
  nombre_en text NOT NULL,
  estado integer NOT NULL DEFAULT 1,
  created_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_by text,
  updated_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_by text
);

CREATE TABLE system.zonas_horarias (
  id_zonas_horarias uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  nombre_iana text NOT NULL UNIQUE,
  estado integer NOT NULL DEFAULT 1,
  created_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_by text,
  updated_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_by text
);

CREATE TABLE system.paises_zonas_horarias (
  id_paises_zonas_horarias uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  fid_paises uuid NOT NULL,
  fid_zonas_horarias uuid NOT NULL,
  estado integer NOT NULL DEFAULT 1,
  created_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  created_by text,
  updated_at timestamptz(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_by text,
  CONSTRAINT paises_zonas_horarias_fid_paises_fkey
    FOREIGN KEY (fid_paises) REFERENCES system.paises(id_paises) ON DELETE CASCADE,
  CONSTRAINT paises_zonas_horarias_fid_zonas_horarias_fkey
    FOREIGN KEY (fid_zonas_horarias) REFERENCES system.zonas_horarias(id_zonas_horarias) ON DELETE CASCADE,
  CONSTRAINT paises_zonas_horarias_fid_paises_fid_zonas_horarias_key
    UNIQUE (fid_paises, fid_zonas_horarias)
);

CREATE INDEX paises_zonas_horarias_fid_zonas_horarias_idx
  ON system.paises_zonas_horarias(fid_zonas_horarias);

